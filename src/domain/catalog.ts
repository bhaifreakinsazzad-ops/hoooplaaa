// ============================================================================

const LAUNCH_START_MS = Date.parse(BRAND_V3.commercialWindow.startIso); // 2026-11-20T00:00:00+06:00
const LAUNCH_END_MS = Date.parse(BRAND_V3.commercialWindow.endIso);     // 2026-12-31T23:59:59+06:00

/**
 * Evaluates whether a given instant falls within the 2026 Launch Offer window
 * (20 Nov 2026 00:00:00 to 31 Dec 2026 23:59:59 Asia/Dhaka).
 */
export function getActivePricingWindow(now: Date = new Date()): PricingWindowState {
  const ts = now.getTime();
  const isLaunchActive = ts >= LAUNCH_START_MS && ts <= LAUNCH_END_MS;
  return {
    activeTier: isLaunchActive ? 'launch_2026' : 'standard_list',
    isLaunchActive,
    labelEn: isLaunchActive
      ? BRAND_V3.commercialWindow.labelEn
      : 'Standard List Rates (Rev 4.4)',
    labelBn: isLaunchActive
      ? BRAND_V3.commercialWindow.labelBn
      : 'স্ট্যান্ডার্ড লিস্ট রেট (Rev 4.4)',
    windowStartIso: BRAND_V3.commercialWindow.startIso,
    windowEndIso: BRAND_V3.commercialWindow.endIso,
    timezone: 'Asia/Dhaka',
    evaluatedAtIso: now.toISOString(),
  };
}

/**
 * Returns the authoritative minor-unit price (Poisha) for a service at `now`.
 * Legacy compatibility SKUs retain their fixed registry basePriceMinor verbatim.
 */
export function getEffectivePriceMinor(service: Service, now: Date = new Date()): number {
  if (service.isLegacyCompat) {
    return service.basePriceMinor;
  }
  const win = getActivePricingWindow(now);
  if (win.isLaunchActive && typeof service.launchPriceMinor === 'number') {
    return service.launchPriceMinor;
  }
  if (typeof service.regularPriceMinor === 'number') {
    return service.regularPriceMinor;
  }
  return service.basePriceMinor;
}

export function formatBdt(minor: number): string {
  const bdt = Math.round(minor / 100);
  return `৳${bdt.toLocaleString('en-US')}`;
}

function toMinor(bdt: number): number {
  return Math.round(bdt * 100);
}

