import { NextRequest, NextResponse } from 'next/server';
import crypto from 'crypto';
import { calculateServerQuote } from '@/domain/pricing-engine';
import { persistentDB } from '@/domain/persistent-db';
import { authenticateRequest } from '@/domain/auth-guard';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const {
      businessId = 'biz_guest',
      businessName,
      businessProfile = {},
      selectedPlatformSkus = [],
      selectedAddonSkus = [],
    } = body;

    if (!businessName || typeof businessName !== 'string' || !businessName.trim()) {
      return NextResponse.json(
        { error: 'Business Name is required to generate an authoritative quote.' },
        { status: 400 }
      );
    }

    const auth = await authenticateRequest(req);

    // Server-authoritative pricing & eligibility calculation (ignores any client price inputs)
    const quote = calculateServerQuote({
      businessId: auth.authenticated ? auth.user.organizationId : businessId,
      businessName: businessName.trim(),
      businessProfile,
      selectedPlatformSkus,
      selectedAddonSkus,
    });

    const customerId = auth.authenticated ? auth.user.id : undefined;
    const organizationId = auth.authenticated ? auth.user.organizationId : undefined;

    // Cryptographic single-use capability token for guest quote claiming
    const claimToken = !auth.authenticated ? crypto.randomBytes(32).toString('hex') : undefined;
    const claimTokenHash = claimToken
      ? crypto.createHash('sha256').update(claimToken).digest('hex')
      : undefined;

    const enrichedQuote = {
      ...quote,
      customerId,
      organizationId,
      claimToken,
      claimTokenHash,
    };

    // Await durable relational persistence
    await persistentDB.saveQuote(enrichedQuote, customerId, organizationId);

    return NextResponse.json({
      success: true,
      quote: enrichedQuote,
    });
  } catch (error: any) {
    return NextResponse.json(
      { error: error?.message || 'Error calculating server quote.' },
      { status: 400 }
    );
  }
}

export async function GET(req: NextRequest) {
  const quoteId = req.nextUrl.searchParams.get('id');
  if (!quoteId) {
    return NextResponse.json({ error: 'Quote ID is required.' }, { status: 400 });
  }

  const quote = await persistentDB.getQuote(quoteId);
  if (!quote) {
    return NextResponse.json({ error: 'Quote not found.' }, { status: 404 });
  }

  // 1. Expiration Verification
  if (new Date(quote.expiresAt) < new Date()) {
    return NextResponse.json(
      { error: 'Quote snapshot has expired. Please configure a new quote.' },
      { status: 410 }
    );
  }

  // 2. Ownership & Privacy Check
  // If the quote was generated by or attached to an authenticated customer/tenant:
  const attachedCustomerId = (quote as any).customerId;
  const attachedOrgId = (quote as any).organizationId;

  if (attachedCustomerId || attachedOrgId) {
    const auth = await authenticateRequest(req);
    if (!auth.authenticated) {
      return NextResponse.json(
        { error: 'Unauthorized: This quote is attached to an account. Please sign in to view it.' },
        { status: 401 }
      );
    }

    const isStaff = ['admin', 'finance', 'engineer'].includes(auth.user.role);
    const isOwner =
      auth.user.id === attachedCustomerId ||
      (Boolean(attachedOrgId) && auth.user.organizationId === attachedOrgId);

    if (!isStaff && !isOwner) {
      await persistentDB.recordAuditLog({
        actorId: auth.user.id,
        actorRole: auth.user.role,
        action: 'CROSS_TENANT_QUOTE_ACCESS_DENIED',
        entityType: 'quote',
        entityId: quoteId,
        metadata: {
          attemptedByOrg: auth.user.organizationId,
          quoteOwnerId: attachedCustomerId,
        },
      });
      return NextResponse.json(
        { error: 'Forbidden: You do not have permission to access this quote.' },
        { status: 403 }
      );
    }
  }

  return NextResponse.json({ success: true, quote });
}
